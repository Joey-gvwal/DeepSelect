#!/usr/bin/env python3
"""生成 deep_select/_build_info.py：把构建矩阵写进 wheel，供运行时兼容性检查。

用法：
  deepselect-gen-build-info --output deep_select/_build_info.py \
      --public-version 1.1.0 \
      --local-label musa5.2.0torch2.11.0.post1 \
      --metadata /out/build-metadata.txt

设计意图：wheel 里必须能回答“我是用哪套 Python/torch/torch_musa/MUSA SDK/子模块
commit 编出来的”。运行时 compat 检查用它给出可执行的报错信息，发布审计用它
生成兼容矩阵表。local label 公式见 WHEEL-TAG-SPEC.md：
    musa<MUSA_SDK_VERSION>torch<torch_public_version>[.b<N>]
"""
from __future__ import annotations

import argparse
import datetime as _dt
import pathlib


def _read_metadata(path: pathlib.Path) -> dict[str, str]:
    meta: dict[str, str] = {}
    if not path.is_file():
        return meta
    for line in path.read_text().splitlines():
        if "=" in line:
            k, v = line.split("=", 1)
            meta[k.strip()] = v.strip()
    return meta


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--output", type=pathlib.Path, required=True)
    ap.add_argument("--public-version", required=True)
    ap.add_argument("--local-label", required=True,
                    help="如 musa5.2.0torch2.11.0.post1（不要带 public 前缀和 +）")
    ap.add_argument("--metadata", type=pathlib.Path, default=None)
    ap.add_argument("--kind", default="wheel", choices=["wheel", "sdist-local"])
    args = ap.parse_args()

    meta = _read_metadata(args.metadata) if args.metadata else {}
    full_version = (
        f"{args.public_version}+{args.local_label}"
        if args.local_label
        else args.public_version
    )
    content = f'''"""Generated by scripts/ci/musa/gen_build_info.py at build time. Do not edit."""

PUBLIC_VERSION = {args.public_version!r}
LOCAL_LABEL = {args.local_label!r}          # musa<SDK>torch<torch public>[.bN]
FULL_VERSION = {full_version!r}
BUILD_KIND = {args.kind!r}
BUILD_PYTHON = {meta.get("build_python", "unknown")!r}
BUILD_TORCH = {meta.get("build_torch", "unknown")!r}
BUILD_TORCH_PUBLIC = {meta.get("build_torch_public", "unknown")!r}
BUILD_TORCH_MUSA = {meta.get("build_torch_musa", "unknown")!r}
BUILD_MUSA_HOME = {meta.get("musa_home", "/usr/local/musa")!r}
BUILD_MUSA_SDK = {meta.get("musa_sdk", "unknown")!r}
BUILD_ARCH = "mp_31"
BUILD_GIT_HEAD = {meta.get("git_head", "unknown")!r}
BUILD_MUTLASS_COMMIT = {meta.get("mutlass_commit", "unknown")!r}
BUILD_CUTLASS_COMMIT = {meta.get("cutlass_commit", "unknown")!r}
BUILD_TIME_UTC = {_dt.datetime.now(_dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")!r}
'''
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(content)
    print(f"wrote {args.output} ({args.public_version}+{args.local_label})")


if __name__ == "__main__":
    main()
